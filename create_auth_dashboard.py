def auth_saved_search(title: str, object_id: str, description: str, extra_filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    attributes = {
        "title": title,
        "description": description,
        "hits": 0,
        "columns": ["timestamp", "agent.name", "rule.level", "rule.description", "data.srcip", "data.srcuser", "data.dstuser", "location"],
        "sort": [["timestamp", "desc"]],
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(search_source(extra_filters), separators=(",", ":"))},
    }
    return saved_object("search", object_id, attributes)


def saved_search() -> Dict[str, Any]:
    return auth_saved_search(
        "Authentication events - latest",
        "search-wazuh-auth-latest",
        "Recent authentication and SSH events captured by Wazuh.",
    )


