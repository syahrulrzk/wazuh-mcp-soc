#!/usr/bin/env python3
"""Generate and install a Wazuh authentication/SSH dashboard saved object."""

import argparse
import datetime as dt
import json
import os
import ssl
import urllib.request
from pathlib import Path
from typing import Any, Dict, List

BASE_URL = os.getenv("WAZUH_INDEXER_URL", "https://localhost:9200").rstrip("/")
CERT = os.getenv("WAZUH_INDEXER_CERT", "/etc/wazuh-indexer/certs/admin.pem")
KEY = os.getenv("WAZUH_INDEXER_KEY", "/etc/wazuh-indexer/certs/admin-key.pem")
CA = os.getenv("WAZUH_INDEXER_CA", "/etc/wazuh-indexer/certs/root-ca.pem")
KIBANA_INDEX = os.getenv("WAZUH_KIBANA_INDEX", ".kibana")
INDEX_PATTERN_ID = "wazuh-alerts-*"
OUT_DIR = Path(os.getenv("WAZUH_MCP_DASHBOARD_DIR", Path(__file__).resolve().parent / "dashboards"))
OUT_FILE = OUT_DIR / "wazuh-authentication-overview.ndjson"

LEVEL_COLORS = {"3": "#8bc34a", "4": "#cddc39", "5": "#ffbf00", "6": "#ff9f1c", "7": "#ff7f0e", "8": "#f4511e", "10": "#d62728", "12": "#800026"}
RULE_COLORS = {
    "sshd: authentication success.": "#2ca02c",
    "PAM: Login session opened.": "#2ca02c",
    "PAM: Login session closed.": "#17becf",
    "PAM: User login failed.": "#ff7f0e",
    "sshd: authentication failed.": "#d62728",
    "sshd: Attempt to login using a non-existent user": "#b10026",
    "PAM: Multiple failed logins in a small period of time.": "#800026",
    "sshd: brute force trying to get access to the system. Non existent user.": "#800026",
    "sshd: brute force trying to get access to the system. Authentication failed.": "#800026",
}
LOGIN_RESULT_COLORS = {"Failed login": "#d62728", "Successful login": "#2ca02c"}


def ssl_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context(cafile=CA if Path(CA).exists() else None)
    ctx.check_hostname = False
    ctx.load_cert_chain(certfile=CERT, keyfile=KEY)
    return ctx


def os_request(method: str, path: str, body: bytes, content_type: str = "application/json") -> Dict[str, Any]:
    req = urllib.request.Request(BASE_URL + path, method=method, data=body, headers={"Content-Type": content_type, "Accept": "application/json"})
    with urllib.request.urlopen(req, context=ssl_context(), timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def auth_filter() -> List[Dict[str, Any]]:
    return [
        {
            "meta": {"disabled": False, "negate": False, "alias": "Authentication / SSH", "type": "custom"},
            "query": {
                "bool": {
                    "should": [
                        {"terms": {"rule.groups": ["authentication_failed", "authentication_success", "sshd", "pam", "sudo", "access_control"]}},
                        {"wildcard": {"location": "*auth.log*"}},
                        {"wildcard": {"location": "*secure*"}},
                        {"term": {"decoder.name": "sshd"}},
                        {"term": {"decoder.name": "pam"}},
                    ],
                    "minimum_should_match": 1,
                }
            },
        }
    ]


def search_source(extra_filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    filters = auth_filter()
    if extra_filters:
        filters.extend(extra_filters)
    return {"indexRefName": "kibanaSavedObjectMeta.searchSourceJSON.index", "query": {"query": "", "language": "kuery"}, "filter": filters}


def count_metric() -> Dict[str, Any]:
    return {"id": "1", "enabled": True, "type": "count", "schema": "metric", "params": {}}


def vis_base(
    title: str,
    vis_type: str,
    aggs: List[Dict[str, Any]],
    params: Dict[str, Any],
    colors: Dict[str, str] = None,
    extra_filters: List[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    return {
        "title": title,
        "visState": json.dumps({"title": title, "type": vis_type, "params": params, "aggs": aggs}, separators=(",", ":")),
        "uiStateJSON": json.dumps({"vis": {"colors": colors or {}}}, separators=(",", ":")),
        "description": "Generated by wazuh-mcp for authentication and SSH triage.",
        "version": 1,
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(search_source(extra_filters), separators=(",", ":"))},
    }


def metric(title: str, object_id: str, sub_text: str, extra_filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    params = {
        "type": "metric",
        "addTooltip": True,
        "addLegend": False,
        "metric": {
            "percentageMode": False,
            "useRanges": False,
            "colorSchema": "Green to Red",
            "metricColorMode": "None",
            "labels": {"show": True},
            "invertColors": False,
            "style": {"bgFill": "#000", "bgColor": False, "labelColor": False, "subText": sub_text, "fontSize": 48},
        },
    }
    return saved_object("visualization", object_id, vis_base(title, "metric", [count_metric()], params, extra_filters=extra_filters))


def failed_filter() -> Dict[str, Any]:
    return {
        "meta": {"disabled": False, "negate": False, "alias": "Failed login", "type": "custom"},
        "query": {"terms": {"rule.groups": ["authentication_failed", "invalid_login", "authentication_failures"]}},
    }


def success_filter() -> Dict[str, Any]:
    return {
        "meta": {"disabled": False, "negate": False, "alias": "Successful login", "type": "custom"},
        "query": {"term": {"rule.groups": "authentication_success"}},
    }


def login_result_pie() -> Dict[str, Any]:
    params = {
        "type": "pie",
        "addTooltip": True,
        "addLegend": True,
        "legendPosition": "right",
        "isDonut": True,
        "labels": {"show": True, "values": True, "last_level": True, "truncate": 100},
    }
    aggs = [
        count_metric(),
        {
            "id": "2",
            "enabled": True,
            "type": "filters",
            "schema": "segment",
            "params": {
                "filters": [
                    {
                        "input": {
                            "query": "rule.groups:authentication_failed or rule.groups:invalid_login or rule.groups:authentication_failures",
                            "language": "kuery",
                        },
                        "label": "Failed login",
                    },
                    {
                        "input": {"query": "rule.groups:authentication_success", "language": "kuery"},
                        "label": "Successful login",
                    },
                ]
            },
        },
    ]
    return saved_object("visualization", "viz-wazuh-auth-login-result-pie", vis_base("Login result mix", "pie", aggs, params, LOGIN_RESULT_COLORS))


