#!/usr/bin/env python3
"""Generate and install a Wazuh access anomaly dashboard saved object."""

import argparse
import datetime as dt
import json
import os
import ssl
import urllib.request
from pathlib import Path
from typing import Any, Dict, List


BASE_URL = os.getenv("WAZUH_INDEXER_URL", "https://localhost:9200").rstrip("/")
CERT = os.getenv("WAZUH_INDEXER_CERT", "/etc/wazuh-indexer/certs/admin.pem")
KEY = os.getenv("WAZUH_INDEXER_KEY", "/etc/wazuh-indexer/certs/admin-key.pem")
CA = os.getenv("WAZUH_INDEXER_CA", "/etc/wazuh-indexer/certs/root-ca.pem")
KIBANA_INDEX = os.getenv("WAZUH_KIBANA_INDEX", ".kibana")
INDEX_PATTERN_ID = "wazuh-alerts-*"
OUT_DIR = Path(os.getenv("WAZUH_MCP_DASHBOARD_DIR", Path(__file__).resolve().parent / "dashboards"))
OUT_FILE = OUT_DIR / "wazuh-access-anomaly.ndjson"


ANOMALY_QUERY = (
    "data.id:200 and ("
    "rule.groups:attack or rule.groups:web_scan or rule.groups:recon or rule.groups:sql_injection "
    "or (rule.description:*SQL* and rule.description:*injection*) "
    "or (rule.description:*Common* and rule.description:*web* and rule.description:*attack*) "
    "or (rule.description:*Suspicious* and rule.description:*URL*) or rule.description:*CMS* "
    "or data.url:*union* or data.url:*select* or data.url:*../* or data.url:*..%2f* "
    "or data.url:*%2e%2e* or data.url:*.env* or data.url:*.git* "
    "or data.url:*config* or data.url:*backup* or data.url:*wp-login* "
    "or data.url:*wp-admin* or data.url:*xmlrpc*)"
)

