#!/usr/bin/env python3
"""Generate and install a Wazuh SOC priority queue dashboard."""

import argparse
import datetime as dt
import json
import os
import ssl
import urllib.request
from pathlib import Path
from typing import Any, Dict, List, Tuple


BASE_URL = os.getenv("WAZUH_INDEXER_URL", "https://localhost:9200").rstrip("/")
CERT = os.getenv("WAZUH_INDEXER_CERT", "/etc/wazuh-indexer/certs/admin.pem")
KEY = os.getenv("WAZUH_INDEXER_KEY", "/etc/wazuh-indexer/certs/admin-key.pem")
CA = os.getenv("WAZUH_INDEXER_CA", "/etc/wazuh-indexer/certs/root-ca.pem")
KIBANA_INDEX = os.getenv("WAZUH_KIBANA_INDEX", ".kibana")
ALERT_PATTERN_ID = "wazuh-alerts-*"
VULN_PATTERN_ID = "wazuh-states-vulnerabilities-*"
OUT_DIR = Path(os.getenv("WAZUH_MCP_DASHBOARD_DIR", Path(__file__).resolve().parent / "dashboards"))
OUT_FILE = OUT_DIR / "wazuh-soc-priority-queue.ndjson"

FAILED_QUERY = "rule.groups:(authentication_failed or invalid_login or authentication_failures)"
SUCCESS_QUERY = "rule.groups:authentication_success"
BRUTE_QUERY = "rule.id:(5712 or 5763) or rule.description:*brute*"
HIGH_ALERT_QUERY = "rule.level >= 10"
ACCESS_ANOMALY_QUERY = (
    "data.id:200 and (rule.groups:attack or rule.groups:web_scan or rule.groups:recon "
    "or rule.groups:sql_injection or (rule.description:*SQL* and rule.description:*injection*) "
    "or (rule.description:*Common* and rule.description:*web* and rule.description:*attack*) "
    "or (rule.description:*Suspicious* and rule.description:*URL*) or rule.description:*CMS* "
    "or data.url:*union* or data.url:*select* or data.url:*../* or data.url:*..%2f* "
    "or data.url:*%2e%2e* or data.url:*.env* or data.url:*.git* or data.url:*config* "
    "or data.url:*backup* or data.url:*wp-login* or data.url:*wp-admin* or data.url:*xmlrpc*)"
)
PRIORITY_QUERY = f"({HIGH_ALERT_QUERY}) or ({ACCESS_ANOMALY_QUERY}) or ({BRUTE_QUERY}) or ({SUCCESS_QUERY})"
CRITICAL_VULN_QUERY = "vulnerability.severity:Critical"
HIGH_VULN_QUERY = "vulnerability.severity:High"

COLORS = {
    "Level 10+ alert": "#b10026",
    "Attack-like HTTP 200": "#ff7f0e",
    "Brute force": "#800026",
    "Successful login": "#2ca02c",
    "Failed login": "#d62728",
    "Critical vuln": "#b10026",
    "High vuln": "#ff7f0e",
}


def ssl_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context(cafile=CA if Path(CA).exists() else None)
    ctx.check_hostname = False
    ctx.load_cert_chain(certfile=CERT, keyfile=KEY)
    return ctx


def os_request(method: str, path: str, body: bytes, content_type: str = "application/json") -> Dict[str, Any]:
    req = urllib.request.Request(
        BASE_URL + path,
        method=method,
        data=body,
        headers={"Content-Type": content_type, "Accept": "application/json"},
    )
    with urllib.request.urlopen(req, context=ssl_context(), timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def count_metric() -> Dict[str, Any]:
    return {"id": "1", "enabled": True, "type": "count", "schema": "metric", "params": {}}


def source(index_id: str, query: str = "", filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    return {
        "indexRefName": "kibanaSavedObjectMeta.searchSourceJSON.index",
        "query": {"query": query, "language": "kuery"},
        "filter": filters or [],
    }


def saved_object(obj_type: str, obj_id: str, attrs: Dict[str, Any], index_id: str) -> Dict[str, Any]:
    return {"type": obj_type, "id": obj_id, "attributes": attrs, "references": [{"name": "kibanaSavedObjectMeta.searchSourceJSON.index", "type": "index-pattern", "id": index_id}]}


def vis_base(
    title: str,
    obj_id: str,
    vis_type: str,
    aggs: List[Dict[str, Any]],
    params: Dict[str, Any],
    query: str = "",
    index_id: str = ALERT_PATTERN_ID,
    colors: Dict[str, str] = None,
    filters: List[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    attrs = {
        "title": title,
        "visState": json.dumps({"title": title, "type": vis_type, "params": params, "aggs": aggs}, separators=(",", ":")),
        "uiStateJSON": json.dumps({"vis": {"colors": colors or {}}}, separators=(",", ":")),
        "description": "Generated by wazuh-mcp for SOC priority triage.",
        "version": 1,
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(source(index_id, query, filters), separators=(",", ":"))},
    }
    return saved_object("visualization", obj_id, attrs, index_id)


def metric(title: str, obj_id: str, query: str, sub_text: str, index_id: str = ALERT_PATTERN_ID, filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    params = {
        "type": "metric",
        "addTooltip": True,
        "addLegend": False,
        "metric": {
            "percentageMode": False,
            "useRanges": False,
            "colorSchema": "Green to Red",
            "metricColorMode": "None",
            "labels": {"show": True},
            "invertColors": False,
            "style": {"bgFill": "#000", "bgColor": False, "labelColor": False, "subText": sub_text, "fontSize": 42},
        },
    }
    return vis_base(title, obj_id, "metric", [count_metric()], params, query, index_id, filters=filters)


def histogram(title: str, obj_id: str, query: str) -> Dict[str, Any]:
    params = {
        "type": "histogram",
        "grid": {"categoryLines": False, "style": {"color": "#eee"}},
        "categoryAxes": [{"id": "CategoryAxis-1", "type": "category", "position": "bottom", "show": True, "style": {}, "scale": {"type": "linear"}, "labels": {"show": True, "truncate": 100}, "title": {}}],
        "valueAxes": [{"id": "ValueAxis-1", "name": "LeftAxis-1", "type": "value", "position": "left", "show": True, "style": {}, "scale": {"type": "linear", "mode": "normal"}, "labels": {"show": True, "rotate": 0, "filter": False, "truncate": 100}, "title": {"text": "Count"}}],
        "seriesParams": [{"show": True, "type": "line", "mode": "normal", "data": {"label": "Count", "id": "1"}, "valueAxis": "ValueAxis-1", "drawLinesBetweenPoints": True, "showCircles": True}],
        "addTooltip": True,
        "addLegend": False,
        "legendPosition": "right",
        "times": [],
    }
    aggs = [
        count_metric(),
        {"id": "2", "enabled": True, "type": "date_histogram", "schema": "segment", "params": {"field": "timestamp", "interval": "auto", "customInterval": "10m", "min_doc_count": 1, "extended_bounds": {}}},
    ]
    return vis_base(title, obj_id, "histogram", aggs, params, query)


def horizontal_bar(
    title: str,
    obj_id: str,
    field: str,
    query: str,
    size: int = 15,
    index_id: str = ALERT_PATTERN_ID,
    filters: List[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    params = {
        "type": "histogram",
        "grid": {"categoryLines": False, "style": {"color": "#eee"}},
        "categoryAxes": [{"id": "CategoryAxis-1", "type": "category", "position": "left", "show": True, "style": {}, "scale": {"type": "linear"}, "labels": {"show": True, "truncate": 150}, "title": {}}],
        "valueAxes": [{"id": "ValueAxis-1", "name": "LeftAxis-1", "type": "value", "position": "bottom", "show": True, "style": {}, "scale": {"type": "linear", "mode": "normal"}, "labels": {"show": True, "rotate": 0, "filter": False, "truncate": 100}, "title": {"text": "Count"}}],
        "seriesParams": [{"show": True, "type": "histogram", "mode": "normal", "data": {"label": "Count", "id": "1"}, "valueAxis": "ValueAxis-1", "drawLinesBetweenPoints": True, "showCircles": True}],
        "addTooltip": True,
        "addLegend": False,
        "legendPosition": "right",
        "times": [],
    }
    aggs = [
        count_metric(),
        {"id": "2", "enabled": True, "type": "terms", "schema": "segment", "params": {"field": field, "size": size, "order": "desc", "orderBy": "1", "otherBucket": False, "missingBucket": False}},
    ]
    return vis_base(title, obj_id, "histogram", aggs, params, query, index_id, filters=filters)


def pie_filters(title: str, obj_id: str, filters: List[Tuple[str, str]], index_id: str = ALERT_PATTERN_ID) -> Dict[str, Any]:
    params = {"type": "pie", "addTooltip": True, "addLegend": True, "legendPosition": "right", "isDonut": True, "labels": {"show": True, "values": True, "last_level": True, "truncate": 100}}
    aggs = [
        count_metric(),
        {"id": "2", "enabled": True, "type": "filters", "schema": "segment", "params": {"filters": [{"input": {"query": query, "language": "kuery"}, "label": label} for label, query in filters]}},
    ]
    return vis_base(title, obj_id, "pie", aggs, params, "", index_id, COLORS)


def search(
    title: str,
    obj_id: str,
    query: str,
    columns: List[str],
    index_id: str = ALERT_PATTERN_ID,
    filters: List[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    attrs = {
        "title": title,
        "description": "Generated by wazuh-mcp for SOC priority triage.",
        "hits": 0,
        "columns": columns,
        "sort": [] if index_id == VULN_PATTERN_ID else [["timestamp", "desc"]],
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(source(index_id, query, filters), separators=(",", ":"))},
    }
    return saved_object("search", obj_id, attrs, index_id)


def vuln_severity_filter() -> Dict[str, Any]:
    return {
        "meta": {"disabled": False, "negate": False, "alias": "Critical/High vulnerabilities", "type": "custom"},
        "query": {"terms": {"vulnerability.severity": ["Critical", "High"]}},
    }


def vuln_filter(alias: str, severities: List[str]) -> Dict[str, Any]:
    return {
        "meta": {"disabled": False, "negate": False, "alias": alias, "type": "custom"},
        "query": {"terms": {"vulnerability.severity": severities}},
    }


