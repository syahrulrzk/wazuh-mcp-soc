def objects() -> List[Dict[str, Any]]:
    alert_cols = ["timestamp", "agent.name", "rule.level", "rule.description", "data.srcip", "data.dstuser", "data.id", "data.url", "location"]
    vuln_cols = ["agent.name", "vulnerability.severity", "vulnerability.id", "package.name", "package.version"]
    critical_filter = [vuln_filter("Critical vulnerabilities", ["Critical"])]
    high_filter = [vuln_filter("High vulnerabilities", ["High"])]
    critical_high_filter = [vuln_filter("Critical/High vulnerabilities", ["Critical", "High"])]
    return [
        metric("Level 10+ alerts", "viz-wazuh-priority-high-alerts", HIGH_ALERT_QUERY, "High severity"),
        metric("Attack-like HTTP 200", "viz-wazuh-priority-web200", ACCESS_ANOMALY_QUERY, "Successful-looking web attack"),
        metric("Brute force", "viz-wazuh-priority-bruteforce", BRUTE_QUERY, "Credential attack"),
        metric("Successful logins", "viz-wazuh-priority-success", SUCCESS_QUERY, "Review after failures"),
        metric("Critical CVEs", "viz-wazuh-priority-critical-vuln", "", "Vulnerability exposure", VULN_PATTERN_ID, critical_filter),
        metric("High CVEs", "viz-wazuh-priority-high-vuln", "", "Vulnerability exposure", VULN_PATTERN_ID, high_filter),
        pie_filters("Priority signal mix", "viz-wazuh-priority-signal-mix", [("Level 10+ alert", HIGH_ALERT_QUERY), ("Attack-like HTTP 200", ACCESS_ANOMALY_QUERY), ("Brute force", BRUTE_QUERY), ("Successful login", SUCCESS_QUERY), ("Failed login", FAILED_QUERY)]),
        histogram("Priority signals over time", "viz-wazuh-priority-over-time", PRIORITY_QUERY),
        horizontal_bar("Priority hosts by risky alerts", "viz-wazuh-priority-hosts", "agent.name", PRIORITY_QUERY, 20),
        horizontal_bar("Priority source IPs", "viz-wazuh-priority-source-ips", "data.srcip", PRIORITY_QUERY, 20),
        horizontal_bar("Hosts with attack-like HTTP 200", "viz-wazuh-priority-web-hosts", "agent.name", ACCESS_ANOMALY_QUERY, 15),
        horizontal_bar("Hosts with Critical/High CVEs", "viz-wazuh-priority-vuln-hosts", "agent.name", "", 20, VULN_PATTERN_ID, critical_high_filter),
        horizontal_bar("Priority detection rules", "viz-wazuh-priority-rules", "rule.description", PRIORITY_QUERY, 20),
        search("SOC priority alert events - latest", "search-wazuh-priority-events-latest", PRIORITY_QUERY, alert_cols),
        search("SOC priority vulnerability states", "search-wazuh-priority-vuln-latest", "", vuln_cols, VULN_PATTERN_ID, [vuln_severity_filter()]),
        dashboard(),
    ]


def write_ndjson(objs: List[Dict[str, Any]]) -> None:
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    with OUT_FILE.open("w", encoding="utf-8") as handle:
        for obj in objs:
            handle.write(json.dumps(obj, ensure_ascii=False) + "\n")


def install(objs: List[Dict[str, Any]]) -> Dict[str, Any]:
    versions = {"dashboard": "7.9.3", "visualization": "7.10.0", "search": "7.9.3"}
    now = dt.datetime.utcnow().replace(microsecond=0).isoformat() + "Z"
    lines = []
    for obj in objs:
        obj_type = obj["type"]
        source_body = {obj_type: obj["attributes"], "type": obj_type, "references": obj.get("references", []), "migrationVersion": {obj_type: versions[obj_type]}, "updated_at": now}
        lines.append(json.dumps({"index": {"_index": KIBANA_INDEX, "_id": f"{obj_type}:{obj['id']}"}}))
        lines.append(json.dumps(source_body, separators=(",", ":")))
    body = ("\n".join(lines) + "\n").encode("utf-8")
    return os_request("POST", "/_bulk?refresh=true", body, "application/x-ndjson")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--install", action="store_true", help="Install into the local .kibana saved objects index")
    args = parser.parse_args()
    objs = objects()
    write_ndjson(objs)
    result: Dict[str, Any] = {"ndjson": str(OUT_FILE), "objects": [{"type": obj["type"], "id": obj["id"]} for obj in objs]}
    if args.install:
        installed = install(objs)
        result["install_errors"] = installed.get("errors")
        result["installed"] = [{"id": item["index"]["_id"], "status": item["index"]["status"]} for item in installed.get("items", [])]
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
