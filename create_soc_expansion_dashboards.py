def pie_filters(title: str, obj_id: str, filters: List[Tuple[str, str]], index_id: str = ALERT_PATTERN_ID, colors: Dict[str, str] = None) -> Dict[str, Any]:
    params = {
        "type": "pie",
        "addTooltip": True,
        "addLegend": True,
        "legendPosition": "right",
        "isDonut": True,
        "labels": {"show": True, "values": True, "last_level": True, "truncate": 100},
    }
    aggs = [
        count_metric(),
        {
            "id": "2",
            "enabled": True,
            "type": "filters",
            "schema": "segment",
            "params": {"filters": [{"input": {"query": query, "language": "kuery"}, "label": label} for label, query in filters]},
        },
    ]
    return vis_base(title, obj_id, "pie", aggs, params, index_id, "", colors)


def search(title: str, obj_id: str, query: str, columns: List[str], index_id: str = ALERT_PATTERN_ID, filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    attrs = {
        "title": title,
        "description": "Generated by wazuh-mcp SOC expansion.",
        "hits": 0,
        "columns": columns,
        "sort": [] if index_id == VULN_PATTERN_ID else [["timestamp", "desc"]],
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(source(index_id, query, filters), separators=(",", ":"))},
    }
    return saved_object("search", obj_id, attrs, index_id)


def vuln_filter(alias: str, severities: List[str]) -> Dict[str, Any]:
    return {
        "meta": {"disabled": False, "negate": False, "alias": alias, "type": "custom"},
        "query": {"terms": {"vulnerability.severity": severities}},
    }


def dashboard(title: str, obj_id: str, description: str, layout: List[Tuple[str, str, int, int, int, int]]) -> Dict[str, Any]:
    panels, refs = [], []
    for idx, (typ, panel_id, x, y, w, h) in enumerate(layout):
        ref = f"panel_{idx}"
        panels.append({"version": "7.10.2", "gridData": {"x": x, "y": y, "w": w, "h": h, "i": str(idx + 1)}, "panelIndex": str(idx + 1), "embeddableConfig": {}, "panelRefName": ref})
        refs.append({"name": ref, "type": typ, "id": panel_id})
    attrs = {
        "title": title,
        "description": description,
        "hits": 0,
        "optionsJSON": json.dumps({"useMargins": True, "hidePanelTitles": False}, separators=(",", ":")),
        "panelsJSON": json.dumps(panels, separators=(",", ":")),
        "timeRestore": True,
        "timeFrom": "now-24h",
        "timeTo": "now",
        "version": 1,
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps({"query": {"query": "", "language": "kuery"}, "filter": []}, separators=(",", ":"))},
    }
    return {"type": "dashboard", "id": obj_id, "attributes": attrs, "references": refs}


