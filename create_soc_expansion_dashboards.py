def ssl_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context(cafile=CA if Path(CA).exists() else None)
    ctx.check_hostname = False
    ctx.load_cert_chain(certfile=CERT, keyfile=KEY)
    return ctx


def os_request(method: str, path: str, body: bytes, content_type: str = "application/json") -> Dict[str, Any]:
    req = urllib.request.Request(
        BASE_URL + path,
        method=method,
        data=body,
        headers={"Content-Type": content_type, "Accept": "application/json"},
    )
    with urllib.request.urlopen(req, context=ssl_context(), timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def count_metric() -> Dict[str, Any]:
    return {"id": "1", "enabled": True, "type": "count", "schema": "metric", "params": {}}


def source(index_id: str, query: str = "", filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    return {
        "indexRefName": "kibanaSavedObjectMeta.searchSourceJSON.index",
        "query": {"query": query, "language": "kuery"},
        "filter": filters or [],
    }


def saved_object(obj_type: str, obj_id: str, attributes: Dict[str, Any], index_id: str) -> Dict[str, Any]:
    return {
        "type": obj_type,
        "id": obj_id,
        "attributes": attributes,
        "references": [
            {
                "name": "kibanaSavedObjectMeta.searchSourceJSON.index",
                "type": "index-pattern",
                "id": index_id,
            }
        ],
    }


def vis_base(
    title: str,
    obj_id: str,
    vis_type: str,
    aggs: List[Dict[str, Any]],
    params: Dict[str, Any],
    index_id: str = ALERT_PATTERN_ID,
    query: str = "",
    colors: Dict[str, str] = None,
    filters: List[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    attrs = {
        "title": title,
        "visState": json.dumps({"title": title, "type": vis_type, "params": params, "aggs": aggs}, separators=(",", ":")),
        "uiStateJSON": json.dumps({"vis": {"colors": colors or {}}}, separators=(",", ":")),
        "description": "Generated by wazuh-mcp SOC expansion.",
        "version": 1,
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(source(index_id, query, filters), separators=(",", ":"))},
    }
    return saved_object("visualization", obj_id, attrs, index_id)


def metric(title: str, obj_id: str, query: str, sub_text: str, index_id: str = ALERT_PATTERN_ID, filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    params = {
        "type": "metric",
        "addTooltip": True,
        "addLegend": False,
        "metric": {
            "percentageMode": False,
            "useRanges": False,
            "colorSchema": "Green to Red",
            "metricColorMode": "None",
            "labels": {"show": True},
            "invertColors": False,
            "style": {"bgFill": "#000", "bgColor": False, "labelColor": False, "subText": sub_text, "fontSize": 42},
        },
    }
    return vis_base(title, obj_id, "metric", [count_metric()], params, index_id, query, filters=filters)


