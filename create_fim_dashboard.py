#!/usr/bin/env python3
"""Generate and install a Wazuh FIM dashboard saved object."""

import argparse
import datetime as dt
import json
import os
import ssl
import urllib.request
from pathlib import Path
from typing import Any, Dict, List, Tuple


BASE_URL = os.getenv("WAZUH_INDEXER_URL", "https://localhost:9200").rstrip("/")
CERT = os.getenv("WAZUH_INDEXER_CERT", "/etc/wazuh-indexer/certs/admin.pem")
KEY = os.getenv("WAZUH_INDEXER_KEY", "/etc/wazuh-indexer/certs/admin-key.pem")
CA = os.getenv("WAZUH_INDEXER_CA", "/etc/wazuh-indexer/certs/root-ca.pem")
KIBANA_INDEX = os.getenv("WAZUH_KIBANA_INDEX", ".kibana")
INDEX_PATTERN_ID = "wazuh-alerts-*"
OUT_DIR = Path(os.getenv("WAZUH_MCP_DASHBOARD_DIR", Path(__file__).resolve().parent / "dashboards"))
OUT_FILE = OUT_DIR / "wazuh-fim-overview.ndjson"

EVENT_COLORS = {"added": "#2ca02c", "modified": "#ffbf00", "deleted": "#d62728"}


def ssl_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context(cafile=CA if Path(CA).exists() else None)
    ctx.check_hostname = False
    ctx.load_cert_chain(certfile=CERT, keyfile=KEY)
    return ctx


def os_request(method: str, path: str, body: bytes, content_type: str = "application/json") -> Dict[str, Any]:
    req = urllib.request.Request(
        BASE_URL + path,
        method=method,
        data=body,
        headers={"Content-Type": content_type, "Accept": "application/json"},
    )
    with urllib.request.urlopen(req, context=ssl_context(), timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def fim_filter() -> Dict[str, Any]:
    return {
        "meta": {"disabled": False, "negate": False, "alias": "FIM / syscheck", "type": "custom"},
        "query": {"term": {"rule.groups": "syscheck"}},
    }


def source(query: str = "", filters: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    return {
        "indexRefName": "kibanaSavedObjectMeta.searchSourceJSON.index",
        "query": {"query": query, "language": "kuery"},
        "filter": filters if filters is not None else [fim_filter()],
    }


def count_metric() -> Dict[str, Any]:
    return {"id": "1", "enabled": True, "type": "count", "schema": "metric", "params": {}}


def saved_object(obj_type: str, obj_id: str, attrs: Dict[str, Any]) -> Dict[str, Any]:
    return {
        "type": obj_type,
        "id": obj_id,
        "attributes": attrs,
        "references": [{"name": "kibanaSavedObjectMeta.searchSourceJSON.index", "type": "index-pattern", "id": INDEX_PATTERN_ID}],
    }


def vis_base(title: str, obj_id: str, vis_type: str, aggs: List[Dict[str, Any]], params: Dict[str, Any], query: str = "", colors: Dict[str, str] = None) -> Dict[str, Any]:
    attrs = {
        "title": title,
        "visState": json.dumps({"title": title, "type": vis_type, "params": params, "aggs": aggs}, separators=(",", ":")),
        "uiStateJSON": json.dumps({"vis": {"colors": colors or {}}}, separators=(",", ":")),
        "description": "Generated by wazuh-mcp for FIM/syscheck triage.",
        "version": 1,
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(source(query), separators=(",", ":"))},
    }
    return saved_object("visualization", obj_id, attrs)


def metric(title: str, obj_id: str, query: str, sub_text: str) -> Dict[str, Any]:
    params = {
        "type": "metric",
        "addTooltip": True,
        "addLegend": False,
        "metric": {
            "percentageMode": False,
            "useRanges": False,
            "colorSchema": "Green to Red",
            "metricColorMode": "None",
            "labels": {"show": True},
            "invertColors": False,
            "style": {"bgFill": "#000", "bgColor": False, "labelColor": False, "subText": sub_text, "fontSize": 42},
        },
    }
    return vis_base(title, obj_id, "metric", [count_metric()], params, query)


