#!/usr/bin/env python3
"""Generate and install a Wazuh SSH brute force dashboard saved object."""

import argparse
import datetime as dt
import json
import os
import ssl
import urllib.request
from pathlib import Path
from typing import Any, Dict, List

BASE_URL = os.getenv("WAZUH_INDEXER_URL", "https://localhost:9200").rstrip("/")
CERT = os.getenv("WAZUH_INDEXER_CERT", "/etc/wazuh-indexer/certs/admin.pem")
KEY = os.getenv("WAZUH_INDEXER_KEY", "/etc/wazuh-indexer/certs/admin-key.pem")
CA = os.getenv("WAZUH_INDEXER_CA", "/etc/wazuh-indexer/certs/root-ca.pem")
KIBANA_INDEX = os.getenv("WAZUH_KIBANA_INDEX", ".kibana")
INDEX_PATTERN_ID = "wazuh-alerts-*"
OUT_DIR = Path(os.getenv("WAZUH_MCP_DASHBOARD_DIR", Path(__file__).resolve().parent / "dashboards"))
OUT_FILE = OUT_DIR / "wazuh-ssh-bruteforce-deep-dive.ndjson"

LEVEL_COLORS = {"3": "#2ca02c", "4": "#cddc39", "5": "#ffbf00", "8": "#f4511e", "10": "#d62728"}
RULE_COLORS = {
    "sshd: authentication success.": "#2ca02c",
    "sshd: authentication failed.": "#d62728",
    "sshd: Attempt to login using a non-existent user": "#b10026",
    "sshd: brute force trying to get access to the system. Non existent user.": "#800026",
    "sshd: brute force trying to get access to the system. Authentication failed.": "#800026",
    "sshd: connection reset": "#ff9f1c",
}


def ssl_context() -> ssl.SSLContext:
    ctx = ssl.create_default_context(cafile=CA if Path(CA).exists() else None)
    ctx.check_hostname = False
    ctx.load_cert_chain(certfile=CERT, keyfile=KEY)
    return ctx


def os_request(method: str, path: str, body: bytes, content_type: str = "application/json") -> Dict[str, Any]:
    req = urllib.request.Request(BASE_URL + path, method=method, data=body, headers={"Content-Type": content_type, "Accept": "application/json"})
    with urllib.request.urlopen(req, context=ssl_context(), timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def base_filter() -> List[Dict[str, Any]]:
    return [
        {
            "meta": {"disabled": False, "negate": False, "alias": "SSH only", "type": "custom"},
            "query": {"term": {"decoder.name": "sshd"}},
        }
    ]


def filter_query(alias: str, query: Dict[str, Any]) -> Dict[str, Any]:
    return {"meta": {"disabled": False, "negate": False, "alias": alias, "type": "custom"}, "query": query}


def failed_filter() -> Dict[str, Any]:
    return filter_query("SSH failed", {"terms": {"rule.groups": ["authentication_failed", "invalid_login", "authentication_failures"]}})


def success_filter() -> Dict[str, Any]:
    return filter_query("SSH success", {"term": {"rule.groups": "authentication_success"}})


def brute_filter() -> Dict[str, Any]:
    return filter_query(
        "SSH brute force",
        {
            "bool": {
                "should": [
                    {"term": {"rule.id": "5712"}},
                    {"term": {"rule.id": "5763"}},
                    {"wildcard": {"rule.description": "*brute force*"}},
                ],
                "minimum_should_match": 1,
            }
        },
    )


def root_filter() -> Dict[str, Any]:
    return filter_query("Target user root", {"term": {"data.dstuser": "root"}})


def search_source(extra: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    filters = base_filter()
    if extra:
        filters.extend(extra)
    return {"indexRefName": "kibanaSavedObjectMeta.searchSourceJSON.index", "query": {"query": "", "language": "kuery"}, "filter": filters}


def count_metric() -> Dict[str, Any]:
    return {"id": "1", "enabled": True, "type": "count", "schema": "metric", "params": {}}


def saved_object(obj_type: str, obj_id: str, attributes: Dict[str, Any]) -> Dict[str, Any]:
    return {"type": obj_type, "id": obj_id, "attributes": attributes, "references": [{"name": "kibanaSavedObjectMeta.searchSourceJSON.index", "type": "index-pattern", "id": INDEX_PATTERN_ID}]}


def vis_base(title: str, vis_type: str, aggs: List[Dict[str, Any]], params: Dict[str, Any], colors: Dict[str, str] = None, extra: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    return {
        "title": title,
        "visState": json.dumps({"title": title, "type": vis_type, "params": params, "aggs": aggs}, separators=(",", ":")),
        "uiStateJSON": json.dumps({"vis": {"colors": colors or {}}}, separators=(",", ":")),
        "description": "Generated by wazuh-mcp for SSH brute force triage.",
        "version": 1,
        "kibanaSavedObjectMeta": {"searchSourceJSON": json.dumps(search_source(extra), separators=(",", ":"))},
    }


def metric(title: str, obj_id: str, sub_text: str, extra: List[Dict[str, Any]] = None) -> Dict[str, Any]:
    params = {
        "type": "metric",
        "addTooltip": True,
        "addLegend": False,
        "metric": {
            "percentageMode": False,
            "useRanges": False,
            "colorSchema": "Green to Red",
            "metricColorMode": "None",
            "labels": {"show": True},
            "invertColors": False,
            "style": {"bgFill": "#000", "bgColor": False, "labelColor": False, "subText": sub_text, "fontSize": 44},
        },
    }
    return saved_object("visualization", obj_id, vis_base(title, "metric", [count_metric()], params, extra=extra))


